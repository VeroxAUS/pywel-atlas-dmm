"""Build the target list for the test-only teleporter (PywelAtlasTest.asi).

What it does:
    Collects named world positions the test teleporter can jump to and writes
    them as a C++ header, so the mod never reads JSON while the game runs.
    Targets, in this order:
      1. two known-safe Abyss Nexus landing spots recorded by the game itself
         in the v0.55 teleport log (good first short hops);
      2. the 8 Bells (data/bell-save-links.json, verified game positions);
      3. the 12 Greymane Shrines (temple object positions from the game's
         level files, or a user in-game check for Kingshield Mountains
         Northern; research/analysis/greymane-shrine-positions.json);
      4. any further fixed spots (EXTRA_SPOTS; none at the moment).
    Any entry with a missing or odd position stops the script with an error
    instead of writing a suspect table.

Reads:  data/bell-save-links.json
        research/analysis/greymane-shrine-positions.json
Writes: src/pywel-atlas/teleport-targets.h (overwritten)
Run:    python -B src/pywel-atlas/prepare_teleport_targets.py
"""
import json
from pathlib import Path

# Landing spots the game used for fast travel in the v0.55 run
# (research/traces/pywel-atlas-v0.55-teleport-observe.log).
NEXUS_SPOTS = [
    ("Southern Guard Post Nexus", (-11793.24, 688.74, -2462.82)),
    ("Hernand Abyss Nexus", (-10626.43, 621.21, -3813.26)),
]
# Further fixed spots (none at the moment). The th.gl Kingshield Mountains
# Northern point was confirmed in game on 2026-10-22 and is now that shrine's
# own position in greymane-shrine-positions.json.
EXTRA_SPOTS = []


def checked(name, position):
    """Return the position as 3 floats, or stop if it is not plausible."""
    if len(position) != 3 or any(type(v) not in (int, float) or abs(v) > 100000 for v in position):
        raise ValueError(f"Unsupported position for {name}")
    return [float(v) for v in position]


def main():
    """Gather all targets and write the C++ header."""
    root = Path(__file__).resolve().parents[2]
    targets = [(name, checked(name, xyz)) for name, xyz in NEXUS_SPOTS]

    bells = json.loads((root / "data" / "bell-save-links.json").read_text(encoding="utf-8"))
    for entry in bells["locations"]:
        targets.append((entry["name"], checked(entry["name"], entry["gamePosition"])))

    shrines = json.loads((root / "research" / "analysis" / "greymane-shrine-positions.json")
                         .read_text(encoding="utf-8"))
    for entry in shrines["shrines"]:
        name = entry["poiName"]
        if entry.get("positionMatch") == "check":
            name += " (game-file shrine)"
        targets.append((name, checked(name, entry["gamePosition"])))

    targets += [(name, checked(name, xyz)) for name, xyz in EXTRA_SPOTS]

    lines = [
        "// Generated by prepare_teleport_targets.py - do not edit by hand.",
        "// Named world positions (X, height Y, Z) for the test-only teleporter.",
        "#pragma once",
        "struct TeleportTarget { const char* name; float position[3]; };",
        "constexpr TeleportTarget kTeleportTargets[] = {",
    ]
    for name, (x, y, z) in targets:
        lines.append(f"    {{{json.dumps(name)}, {{{x!r}f, {y!r}f, {z!r}f}}}},")
    lines.append("};")
    (Path(__file__).resolve().parent / "teleport-targets.h").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(targets)} targets written")


if __name__ == "__main__":
    main()
