"""Generate a build-specific native probe profile from the inspected executable.

What it does, in plain terms:
    The native mod needs to know where certain functions live inside one
    exact version ("build") of the game, and to refuse to run on any other
    build. This script reads the installed game executable and generates:
      - a C++ header file (build-profile.h) containing the build's timestamp
        and image size, plus the first 48 bytes found at each of five
        traced code locations. The mod can compare those bytes at run time
        to confirm it is looking at the expected code before using it.
      - a JSON report (build-profile.json) with the same facts, the file's
        SHA-256 fingerprint and the names/RVAs of the five locations.
    An RVA ("relative virtual address") is a position measured from the
    start of the program as loaded in memory.

Reads: the installed game executable, read-only.
Writes: outputs/tools/native-map/build-profile.h and build-profile.json
under the old workspace root (two folders above this script). Stops with an
error if any 48-byte pattern occurs more than once in the file.

Legacy: written for the original Codex workspace layout; paths may no longer
resolve (outputs/tools/native-map/ is an old folder -- see the path map in
README.md -- pefile is expected in a "deps" folder next to the script, and
the Steam path on drive E: is hard-coded).
"""

import hashlib
import json
import struct
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[2]
image = Path("E:/SteamLibrary/steamapps/common/Crimson Desert/bin64/CrimsonDesert.exe").read_bytes()
# Read the Windows "PE" (Portable Executable) header by hand:
#   offset 0x3C holds where the PE header starts;
#   PE header + 8 holds the build timestamp;
#   PE header + 24 + 56 holds SizeOfImage (program size in memory).
pe = struct.unpack_from("<I", image, 0x3C)[0]
timestamp = struct.unpack_from("<I", image, pe + 8)[0]
image_size = struct.unpack_from("<I", image, pe + 24 + 56)[0]
# Make bundled third-party libraries in ./deps importable (old layout).
sys.path.insert(0, str(Path(__file__).resolve().parent / "deps"))
import pefile

executable = pefile.PE(data=image, fast_load=True)
# These are traced from the actual WorldMap controller's action selectors.
# Names describe the static evidence; runtime correlation remains necessary.
functions = [
    ("find-path-action", 0xDC32E0),
    ("destination-handoff", 0xDEF810),
    ("saved-pin-action", 0xD91EF0),
    ("saved-pin-handoff", 0xB84320),
    ("new-pin-insert", 0x4955A9),
]
# Convert each in-memory RVA to a byte position in the .exe file.
offsets = [executable.get_offset_from_rva(rva) for _, rva in functions]

# Build the C++ header text line by line.
lines = [
    "// Generated by work/map-mod-research/make_profile.py; installed build only.",
    "#pragma once",
    f"constexpr DWORD kExpectedTimestamp = {timestamp}u;",
    f"constexpr DWORD kExpectedImageSize = {image_size}u;",
    "constexpr size_t kContextLength = 48;",
    "constexpr unsigned char kCandidateContexts[5][kContextLength] = {",
]
for offset in offsets:
    context = image[offset : offset + 48]
    # The pattern must be unique, otherwise it could match the wrong code.
    if image.count(context) != 1:
        raise RuntimeError("Candidate context is not unique")
    lines.append("    {")
    # Write the 48 bytes as hex values, 12 per line.
    for start in range(0, len(context), 12):
        lines.append("        " + ", ".join(f"0x{value:02x}" for value in context[start:start+12]) + ",")
    lines.append("    },")
lines.append("};")
target = root / "outputs/tools/native-map/build-profile.h"
target.write_text("\n".join(lines) + "\n", encoding="utf-8")
# Human-readable record of what the profile was generated from.
report = {
    "steamBuildId": "25474236",
    "sha256": hashlib.sha256(image).hexdigest(),
    "peTimestamp": timestamp,
    "imageSize": image_size,
    "functions": [{"name": name, "rva": hex(rva)} for name, rva in functions],
    "purpose": "Controlled Bell placement and observation of newly acknowledged native pin keys.",
}
(root / "outputs/tools/native-map/build-profile.json").write_text(
    json.dumps(report, indent=2) + "\n", encoding="utf-8"
)
